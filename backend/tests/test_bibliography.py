def test_score_counts():
    mk = lambda s: SourceCheck(citation_id="S1", status=s, method="x", detail="")  # noqa: E731
    sc = score([mk("exists"), mk("exists"), mk("not_found"), mk("mismatch"), mk("unreachable"), mk("unchecked")], 6)
    assert sc == {"verified": 2, "total": 6, "fabricated": 1, "distorted": 1, "unreachable": 2}


