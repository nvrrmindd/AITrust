def _parsed(text):
    body, bib = find_bibliography(text)
    refs = split_references(bib)
    return body, refs, [parse_reference(r)[0] for r in refs]


def test_gost_numbered_list():
    body, refs, cits = _parsed(GOST)
    assert [r.n for r in refs] == [1, 2, 3]  # «Приложение А» cut off
    assert cits[0].kind == "academic" and cits[0].title == "Цифровая экономика Казахстана"
    assert cits[0].year == 2021 and cits[0].venue.startswith("Вестник КазНУ") and cits[0].authors == ["Иванов"]
    assert cits[1].kind == "book" and cits[1].year == 2019
    assert cits[2].kind == "web" and cits[2].url == "https://stat.gov.kz/ru/" and not cits[2].venue
    claims = cited_claims(body, cits)
    assert [c.citation_ids for c in claims] == [["S1"], ["S2"]]
    assert "[1, с. 25]" not in claims[0].text and "12%" in claims[0].text


def test_apa_unnumbered_list_with_wrapped_lines():
    body, refs, cits = _parsed(APA)
    assert len(refs) == 2 and refs[0].raw.endswith("s41598-023-41032-5")  # continuation line joined
    assert cits[0].doi == "10.1038/s41598-023-41032-5" and cits[0].authors == ["Walters", "Wilder"]
    assert cits[0].title == "Fabrication and errors in the bibliographic citations generated by ChatGPT"
    assert cits[1].title == "Citation quality in student papers" and cits[1].kind == "book"
    claims = cited_claims(body, cits)
    assert claims[0].citation_ids == ["S1"]
    assert set(claims[1].citation_ids) == {"S1", "S2"}  # (Smith, 2020; Walters, 2023)


def test_bracket_numbered_list():
    body, refs, cits = _parsed(BRACKETS)
    assert [r.n for r in refs] == [1, 2]
    assert cits[0].kind == "web" and "niemanlab.org" in cits[0].url
    assert cits[1].kind == "academic" and cits[1].venue == "Computers & Education"
    assert [c.citation_ids for c in cited_claims(body, cits)] == [["S1"], ["S2"]]


