def _docx_bytes(paragraphs, table=None) -> bytes:
    doc = Document()
    for p in paragraphs:
        doc.add_paragraph(p)
    if table:
        t = doc.add_table(rows=len(table), cols=len(table[0]))
        for i, row in enumerate(table):
            for j, cell in enumerate(row):
                t.cell(i, j).text = cell
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _pdf_bytes(lines) -> bytes:
    """Minimal one-page PDF with a text layer (Helvetica, ASCII)."""
    esc = lambda s: s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")  # noqa: E731
    stream = "BT /F1 11 Tf 14 TL 50 760 Td " + " ".join(f"({esc(ln)}) Tj T*" for ln in lines) + " ET"
    objs = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(stream)} >>\nstream\n{stream}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out, offsets = "%PDF-1.4\n", []
    for i, o in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n{o}\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n" + "".join(f"{o:010d} 00000 n \n" for o in offsets)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF"
    return out.encode("latin-1")


def test_docx_paragraphs_and_tables_in_order():
    data = _docx_bytes(["Рост составил 12% [1].", "Список литературы",
                        "1. Иванов И. И. Цифровая экономика Казахстана // Вестник КазНУ. — 2021. — № 3."],
                       table=[["Показатель", "Значение"], ["Рост", "12%"]])
    text = extract_text("курсовая.docx", data)
    assert text.index("Рост составил") < text.index("Список литературы") < text.index("Показатель | Значение")
    assert find_bibliography(text)


def test_pdf_text_layer():
    text = extract_text("paper.pdf", _pdf_bytes([
        "AI search engines were wrong in more than 60% of queries [1].", "References",
        "[1] Walters, W. H. (2023). Fabrication and errors. Scientific Reports, 13, 14045."]))
    body, bib = find_bibliography(text)
    assert "60%" in body and "Walters" in bib


def test_scanned_pdf_and_bad_inputs():
    with pytest.raises(DocumentError, match="картинка"):
        extract_text("scan.pdf", _pdf_bytes([]))
    with pytest.raises(DocumentError, match="формат"):
        extract_text("work.odt", b"x" * 100)
    with pytest.raises(DocumentError, match="пустой"):
        extract_text("work.txt", b"   ")
    with pytest.raises(DocumentError, match="повреждён"):
        extract_text("work.docx", b"not a zip at all")
    assert extract_text("w.txt", "Список литературы\n1. Тест".encode("cp1251")).startswith("Список литературы")


def test_check_file_endpoint_errors():
    from app.main import app
    c = TestClient(app)
    r = c.post("/api/check-file", files={"file": ("w.odt", b"x" * 50, "application/octet-stream")})
    assert r.status_code == 422 and "формат" in r.json()["detail"]
    r = c.post("/api/check-file", files={"file": ("w.txt", "Текст без списка литературы, но длинный.".encode(), "text/plain")})
    assert r.status_code == 422 and r.json()["detail"] == NO_BIBLIOGRAPHY
    assert c.get("/api/sample-docx").status_code == 200
